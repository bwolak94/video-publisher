import * as crypto from 'crypto';
import { Injectable } from '@nestjs/common';

export type C2paMetadata = {
  title: string;
  models: string[];
  generator: string;
  timestamp: string;
  hasLikeness: boolean;
};

export interface C2paManifestResult {
  manifestId: string;
  manifestJson: string;
}

@Injectable()
export class C2paService {
  /**
   * Creates a C2PA-conformant manifest JSON sidecar for the given MP4.
   * In production, this would be embedded in the MP4 container via c2patool CLI.
   * Returns the manifest JSON string and a manifest ID.
   *
   * @param metadata - AI generation metadata to embed in the manifest
   * @returns Manifest ID (URN) and serialized manifest JSON
   */
  async embedManifest(metadata: C2paMetadata): Promise<C2paManifestResult> {
    const manifestId = `urn:c2pa:ai-video-factory:${crypto.randomUUID()}`;

    const manifest = {
      '@context': 'http://schema.c2pa.org/manifest/v1',
      claim_generator: `${metadata.generator}/1.0 c2pa-node/0.1`,
      manifest_id: manifestId,
      format: 'video/mp4',
      assertions: [
        {
          label: 'c2pa.ai.generative_tool',
          data: {
            description: metadata.hasLikeness
              ? 'Synthetic likeness of a real person generated by AI (deepfake). AI Act Art. 50 disclosure.'
              : 'AI-generated fictional characters.',
            tools: metadata.models.map((m) => ({ name: m, version: '1.0' })),
          },
        },
        {
          label: 'stds.schema-org.CreativeWork',
          data: {
            '@type': 'VideoObject',
            name: metadata.title,
            generator: metadata.generator,
            dateCreated: metadata.timestamp,
          },
        },
        {
          label: 'c2pa.training-mining',
          data: {
            entries: {
              'c2pa.ai_generative_training': { use: 'notAllowed' },
              'c2pa.data_mining': { use: 'notAllowed' },
            },
          },
        },
      ],
      signature_info: {
        alg: 'sha256',
        issuer: 'AI Video Factory',
        time: metadata.timestamp,
        hash: crypto.createHash('sha256').update(JSON.stringify(metadata)).digest('hex'),
      },
    };

    return { manifestId, manifestJson: JSON.stringify(manifest, null, 2) };
  }
}
